import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, realpathSync, symlinkSync, writeFileSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { pathToFileURL } from 'node:url';
import { execFileSync } from 'node:child_process';

const lab = resolve(process.env.OBSERVA_LAB_ROOT);
const packageRoot = resolve(process.env.OBSERVA_LAB_PACKAGE);
const profile = resolve(process.env.OBSERVA_LAB_PROFILE);
assert.ok(lab.endsWith('/observa-qualification/openclaw-v080'));
const bin = join(lab, 'collision-prefix', 'observa prefix', 'bin'); mkdirSync(bin, { recursive: true });
const localNode = join(lab, 'collision-prefix/bin/observa');
const generic = join(bin, 'observa'); const host = join(lab, 'runtime/node_modules/openclaw/openclaw.mjs');
if (!existsSync(generic)) symlinkSync(localNode, generic);
if (!existsSync(join(bin, 'openclaw'))) symlinkSync(host, join(bin, 'openclaw'));
const env = { PATH: `${dirname(process.execPath)}:${bin}:/usr/bin:/bin`, HOME: join(profile, 'home'), OPENCLAW_STATE_DIR: profile };
const sha = path => createHash('sha256').update(readFileSync(path)).digest('hex');
const before = { target: realpathSync(generic), sha256: sha(generic), version: execFileSync(generic, ['--version'], { env, encoding: 'utf8' }) };
assert.match(before.version, /observa-cli 0\.1\.9/);
const { ensureObservaEntrypoint } = await import(pathToFileURL(join(packageRoot, 'plugins/openclaw-connector/cli-entrypoint.mjs')));
const args = { packageRoot, stateDir: join(profile, 'observa-state'), argv1: join(bin, 'openclaw'), env };
const namespaced = ensureObservaEntrypoint({ ...args, entrypointName: 'observa-openclaw' });
assert.ok(['INSTALLED', 'UPDATED', 'CURRENT'].includes(namespaced.state));
const result = ensureObservaEntrypoint({ ...args, namespaced }); assert.equal(result.state, 'COLLISION_LOCAL_NODE');
const entry = join(bin, 'observa-openclaw');
const help = execFileSync(entry, ['access', '--help'], { env, encoding: 'utf8' });
assert.match(help, /Usage: observa-openclaw access/);
const status = execFileSync(entry, ['status'], { env, encoding: 'utf8' });
assert.match(status, /observa on PATH is LOCAL_NODE/);
assert.equal(status.includes(`${bin}/observa`), true);
assert.equal(status.includes('observa-openclaw prefix'), false);
assert.equal(realpathSync(generic), before.target); assert.equal(sha(generic), before.sha256);
assert.equal(execFileSync(generic, ['--version'], { env, encoding: 'utf8' }), before.version);
const evidence = { status: 'PASS', local_node_version: '0.1.9', local_node_entry_sha256: before.sha256, namespace: namespaced.state, generic: result.state, paths_preserved: true, help };
writeFileSync(join(lab, 'evidence/candidate4/real-collision.json'), JSON.stringify(evidence, null, 2));
console.log(JSON.stringify(evidence));
